/**
 * Konu üretici. statKey verilirse ağırlık çıkmış-soru istatistiğinden türetilir;
 * aksi halde fallbackWeight kullanılır.
 */
function mkTopic(
  id: string,
  name: string,
  sectionSubjectKey: string,
  statKey?: string,
  fallbackWeight: SubjectTopic['weight'] = 'ORTA',
  sharedStat = false,
): SubjectTopic {
  const summary = statKey ? getTopicStat(statKey) : null;
  // sharedStat: birden çok alt başlık aynı istatistik satırını paylaşıyor —
  // ağırlığı istatistikten türetmek (her parçaya tüm frekansı vermek) yanıltıcı,
  // elle verilen fallbackWeight kullanılır ama statKey bilgi için korunur.
  const weight =
    summary && !sharedStat
      ? deriveWeight(summary.avgPerYear, sectionSubjectKey)
      : fallbackWeight;
  return { id, name, weight, isStudied: false, isPracticeDone: false, isReviewed: false, statKey };
}

